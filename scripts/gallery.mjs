// Build docs/screenshots/gallery.html from docs/screenshots/** and the panel registry.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'

const reg = readFileSync('src/lib/panels/registry.ts', 'utf8')
const panels = [...reg.matchAll(/\{ id: '([^']+)', title: '([^']+)', workflow: '(\w+)'[\s\S]*?coverage: '([^']+)', patterns: \[([^\]]*)\]/g)].map((m) => ({ id: m[1], title: m[2], wf: m[3], coverage: m[4], patterns: m[5].replace(/'/g, '').split(',').map((s) => s.trim()).filter(Boolean) }))
const compare = [
  ['provenance', 'Provenance and compatibility', ['P4']], ['gof', 'GOF side by side', []], ['overlay', 'Trajectory overlay A vs B', ['P5', 'P6']],
  ['delta-lines', 'Per-state Δ over time', ['P6']], ['delta-raster', 'Δ heatmap', ['P8']], ['params', 'Parameter changes', ['P9', 'P2']],
]
const rejected = {
  P1: 'Rejected everywhere: the bundle stores no additive composition over time; computing W·K drive contributions in the viewer would hard-code the RHS. Never for fold changes/ratios.',
  P2: 'Not for credible intervals (kept quantile-based).',
  P3: 'Overview+detail zoom on time axes not added (14-point grids).',
  P4: 'No pie-style glyphs.',
  P5: 'Never observed vs predicted as an area (sparse observations).',
  P7: 'No monotone/curved segments.',
  P8: 'No random-walk/barycentric interpolation or blur on data; sparse W matrix uses Cell.',
  P9: 'Parameter pairs not faceted on one shared scale (different magnitudes); confidence fixed to 0.95.',
  P10: 'No binX intervals across irregular time grids; always paired with 5–95 % bands.',
  P11: 'No flow fields interpolated between trajectories (needs engine RHS, Milestone 2).',
  P12: "SveltePlot densityX not used (different kernel/bandwidth); PhosKinTime's KDE ported. fy facets replaced by offset baselines (25 facets took ~21 s).",
}
const img = (p, cap) => (existsSync(`docs/screenshots/${p}`) ? `<figure><img loading="lazy" src="${p}" alt="${cap}"><figcaption>${cap}</figcaption></figure>` : '')
let html = `<!doctype html><html><head><meta charset="utf-8"><title>PhosKinTime-Vis gallery (synthetic data)</title>
<style>body{font-family:system-ui,sans-serif;max-width:1400px;margin:20px auto;color:#1d2330}figure{margin:10px 0 24px;border:1px solid #ddd;padding:6px}img{max-width:100%}figcaption{font-size:13px;color:#444}h2{border-bottom:1px solid #ccd}nav a{margin-right:12px}.pat{font-family:monospace;background:#f0f0f0;padding:0 5px;border-radius:6px}.rej{background:#fff4e5;padding:6px 10px;font-size:14px}</style></head><body>
<h1>PhosKinTime-Vis: screenshot gallery</h1>
<p><b>All data is synthetic</b> (spec fixtures from <code>tests/fixtures/make_fixtures.py</code>, DRAFT schema 1.0). Generated by <code>scripts/screenshots.mjs</code> + <code>scripts/gallery.mjs</code> from the single-file build in headless Chromium.</p>
<nav><a href="#small-protwise">protwise</a><a href="#network">networkmodel</a><a href="#partial">partial (not-available cards)</a><a href="#compare">comparison</a><a href="#patterns">patterns</a></nav>`
for (const fx of ['small-protwise', 'network', 'partial']) {
  if (!existsSync(`docs/screenshots/${fx}`)) continue
  html += `<h2 id="${fx}">${fx}</h2>` + img(`${fx}/_header.png`, `${fx}: header, sha256 badge, open issues`)
  const files = new Set(readdirSync(`docs/screenshots/${fx}`))
  for (const p of panels) if (files.has(`${p.id}.png`)) html += img(`${fx}/${p.id}.png`, `${p.id}: ${p.title} [${p.coverage}] ${p.patterns.map((x) => `<span class=pat>${x}</span>`).join(' ')}`)
}
html += `<h2 id="compare">Comparison mode: network (A, before) vs network-after-fix (B, after)</h2>`
for (const [id, t, pats] of compare) html += img(`compare/${id}.png`, `${t} ${pats.map((x) => `<span class=pat>${x}</span>`).join(' ')}`)
html += `<h2 id="patterns">Patterns in use, and where they were rejected</h2>`
for (let i = 1; i <= 12; i++) {
  const P = `P${i}`
  const users = panels.filter((p) => p.patterns.includes(P))
  const cusers = compare.filter((c) => c[2].includes(P))
  html += `<h3>${P}</h3><p>Used in: ${[...users.map((u) => u.id), ...cusers.map((c) => 'compare/' + c[0])].join(', ') || '<i>none</i>'}</p>`
  if (rejected[P]) html += `<p class="rej">Rejected / limited: ${rejected[P]}</p>`
  const shot = users.find((u) => existsSync(`docs/screenshots/network/${u.id}.png`) || existsSync(`docs/screenshots/small-protwise/${u.id}.png`))
  if (shot) html += img(existsSync(`docs/screenshots/network/${shot.id}.png`) ? `network/${shot.id}.png` : `small-protwise/${shot.id}.png`, `${P} example: ${shot.id}`)
  else if (cusers[0]) html += img(`compare/${cusers[0][0]}.png`, `${P} example: compare/${cusers[0][0]}`)
}
html += '</body></html>'
writeFileSync('docs/screenshots/gallery.html', html)
console.log('wrote docs/screenshots/gallery.html')
