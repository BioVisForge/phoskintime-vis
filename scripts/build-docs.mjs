// Build the documentation site into site/: generate the reference, release and screenshot files
// (all ignored by git), run Zensical, then add the live demo (site/demo/) and the screenshot
// gallery (site/gallery/).
// Needs: npm run fixtures, npm run build:single, npm run docs:assets, and
// pip install -r website/requirements.txt (set ZENSICAL to the executable if it is not on PATH).
import { execFileSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createServer } from 'vite'
import { parse } from 'yaml'

const REPO = 'https://github.com/BioVisForge/phoskintime-vis'
const run = (cmd, args) => execFileSync(cmd, args, { stdio: 'inherit' })
const read = (p) => readFileSync(p, 'utf8')
const write = (p, s) => {
  mkdirSync(p.slice(0, p.lastIndexOf('/')), { recursive: true })
  writeFileSync(p, s)
}
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n+/g, ' ')
const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n') + '\n'
const banner = (from) => `<!-- generated by scripts/build-docs.mjs from ${from}: do not edit -->\n\n`

if (!existsSync('docs/screenshots/sections')) {
  console.error('docs/screenshots is missing: run `npm run fixtures && npm run build:single && npm run docs:assets` first')
  process.exit(1)
}

// brand and screenshots
rmSync('website/assets', { recursive: true, force: true })
cpSync('assets/brand', 'website/assets/brand', { recursive: true })
mkdirSync('website/assets/screenshots', { recursive: true })
for (const s of ['overview', 'fit', 'compare']) cpSync(`docs/screenshots/sections/${s}-light.png`, `website/assets/screenshots/${s}.png`)

// panel reference, from the registry itself
const vite = await createServer({ server: { middlewareMode: true, hmr: false }, appType: 'custom', logLevel: 'error' })
const { PANELS } = await vite.ssrLoadModule('/src/lib/panels/registry.ts')
await vite.close()
let panels = banner('src/lib/panels/registry.ts') + `# Panels\n\n${PANELS.length} panels. A panel is drawn when the bundle has the tables it needs.\n`
for (const [workflow, title] of [['protwise', 'protwise'], ['networkmodel', 'networkmodel'], ['any', 'Any workflow']]) {
  const list = PANELS.filter((p) => p.workflow === workflow)
  if (!list.length) continue
  panels += `\n## ${title}\n\n` + table(['Panel', 'What it shows', 'Needs', 'Coverage'], list.map((p) => [`**${p.title}**<br>\`${p.id}\``, p.description, [...p.requires.map((r) => `\`${r.table}\``), ...(p.arrays ?? []).map((a) => `array \`${a}\``)].join(', '), p.coverage]))
}
write('website/guide/panels.md', panels)

// bundle schema, from the contract files
const dir = 'contracts/phoskintime/1.0-draft'
const manifest = JSON.parse(read(`${dir}/manifest.schema.json`))
const tables = JSON.parse(read(`${dir}/tables.json`))
const typeOf = (v) => v.$ref?.split('/').pop() ?? (Array.isArray(v.type) ? v.type.join(' or ') : v.type) ?? (v.enum ? 'enum' : '')
let schema = banner(dir) + `# Bundle schema 1.0 (DRAFT)\n\n!!! warning\n    ${manifest.description}\n\n## manifest.json\n\n`
schema += table(['Field', 'Type', 'Required', 'Notes'], Object.entries(manifest.properties).map(([k, v]) => [`\`${k}\``, typeOf(v), manifest.required.includes(k) ? 'yes' : '', v.description]))
schema += `\nFull JSON Schema: [manifest.schema.json](${REPO}/blob/main/${dir}/manifest.schema.json).\n\n## Tables\n`
for (const [name, t] of Object.entries(tables.tables)) {
  schema += `\n### ${name}\n\n${t.core ? '*Core table.* ' : ''}${t.description ?? ''}\n\n`
  schema += table(['Column', 'Type', 'Nullable', 'Unit'], t.columns.map((c) => [`\`${c.name}\``, c.dtype, c.nullable ? 'yes' : '', c.unit]))
}
write('website/reference/bundle-schema.md', schema)

// engine API, from the OpenAPI file
const apiFile = 'contracts/pktengine/0.1-draft/openapi.yaml'
const api = parse(read(apiFile))
const schemaName = (s) => (!s ? '' : s.$ref ? s.$ref.split('/').pop() : s.type === 'array' ? `array of ${schemaName(s.items)}` : (s.type ?? ''))
let eng = banner(apiFile) + `# Engine API ${api.info.version}\n\n!!! warning\n    A proposal: no engine implements it yet. The viewer talks to \`scripts/mock-engine.mjs\`.\n\nDefault address: \`${api.servers[0].url}\`. [OpenAPI file](${REPO}/blob/main/${apiFile}).\n\n## Endpoints\n`
for (const [path, ops] of Object.entries(api.paths))
  for (const [method, op] of Object.entries(ops)) {
    eng += `\n### ${method.toUpperCase()} \`${path}\`\n\n${op.summary ?? ''}\n\n`
    const body = op.requestBody?.content?.['application/json']?.schema
    if (body) eng += `- Request: \`${schemaName(body)}\`\n`
    for (const [code, r] of Object.entries(op.responses ?? {}))
      eng += `- Response ${code}: ${Object.entries(r.content ?? {}).map(([type, c]) => `\`${type}\`${c.schema ? ` (\`${schemaName(c.schema)}\`)` : ''}`).join(', ')}\n`
  }
eng += '\n## Schemas\n'
for (const [name, s] of Object.entries(api.components.schemas)) {
  eng += `\n### ${name}\n\n`
  if (!s.properties) eng += `${schemaName(s)}\n`
  else eng += table(['Property', 'Type', 'Required', 'Notes'], Object.entries(s.properties).map(([k, v]) => [`\`${k}\``, v.enum ? v.enum.join(' \\| ') : schemaName(v), s.required?.includes(k) ? 'yes' : '', v.description]))
}
write('website/reference/engine-api.md', eng)

// releases (grouped by version), changelog, contributing, security
rmSync('website/releases', { recursive: true, force: true })
const versions = readdirSync('release-notes').filter((f) => /^v\d.*\.md$/.test(f)).map((f) => f.slice(0, -3)).sort((a, b) => b.localeCompare(a, undefined, { numeric: true }))
let index = banner('release-notes/') + '# Releases\n\nNewest first. Commit-level history: [Changelog](changelog.md).\n'
for (const v of versions) {
  const notes = read(`release-notes/${v}.md`).replace(/^# .*\n+/, '')
  index += `\n- [**${v}**](${v}.md) · [download](${REPO}/releases/tag/${v})`
  write(`website/releases/${v}.md`, banner(`release-notes/${v}.md`) + `# ${v}\n\n${notes}`)
}
write('website/releases/index.md', index + '\n')
write('website/releases/changelog.md', banner('CHANGELOG.md') + read('CHANGELOG.md'))
// repository-relative links do not exist on the site
const absolute = (s) => s.replace(/\]\((?!https?:|#|mailto:)([^)]+)\)/g, `](${REPO}/blob/main/$1)`)
write('website/development/contributing.md', banner('CONTRIBUTING.md') + absolute(read('CONTRIBUTING.md')))
write('website/development/security.md', banner('SECURITY.md') + absolute(read('SECURITY.md')))

// TypeScript API
rmSync('website/reference/api', { recursive: true, force: true })
run('npx', ['typedoc'])

rmSync('site', { recursive: true, force: true })
run(process.env.ZENSICAL ?? 'zensical', ['build', '--clean', '--strict'])

// live demo (the app's Pages build with the synthetic bundles) and the gallery
run('npm', ['run', 'build'])
run('node', ['scripts/copy-demo.mjs'])
cpSync('dist', 'site/demo', { recursive: true })
cpSync('docs/screenshots', 'site/gallery/screenshots', { recursive: true })
if (existsSync('docs/samples/exports')) cpSync('docs/samples/exports', 'site/gallery/samples/exports', { recursive: true })
console.log('site/ ready: docs, site/demo/, site/gallery/screenshots/gallery.html')
