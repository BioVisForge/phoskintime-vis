import type { Comparison } from '../derive/compare'
import { toCsv } from '../transforms/table'
import { figureToSvg } from '../export/figure'

const esc = (s: unknown) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!)

/** All deltas of a comparison as one long CSV (kind, key, layer, time, a, b, delta, ratio). */
export function deltasCsv(c: Comparison): string {
  const rows: Record<string, unknown>[] = []
  for (const p of c.params.pairs) rows.push({ kind: 'parameter', key: p.name, group: p.group, layer: null, time: null, a: p.a, b: p.b, delta: p.delta, ratio: p.ratio, log2ratio: p.log2ratio })
  for (const n of c.params.onlyA) rows.push({ kind: 'parameter_only_in_A', key: n })
  for (const n of c.params.onlyB) rows.push({ kind: 'parameter_only_in_B', key: n })
  for (const t of c.traj.pairs) rows.push({ kind: 'trajectory_pred', key: t.state, group: null, layer: t.layer, time: t.time, a: t.a, b: t.b, delta: t.delta })
  for (const s of c.traj.onlyA) rows.push({ kind: 'state_only_in_A', key: s })
  for (const s of c.traj.onlyB) rows.push({ kind: 'state_only_in_B', key: s })
  const g = (name: string, x: { r2: number; rmse: number; sigma: number; n: number }, y: { r2: number; rmse: number; sigma: number; n: number } | undefined) => {
    for (const k of ['r2', 'rmse', 'sigma', 'n'] as const) rows.push({ kind: `gof_${k}`, key: name, layer: name, a: x[k], b: y?.[k] ?? null, delta: y ? y[k] - x[k] : null })
  }
  g('overall', c.gof.a.overall, c.gof.b.overall)
  for (const l of Object.keys(c.gof.a.layers)) g(l, c.gof.a.layers[l], c.gof.b.layers[l])
  for (const m of c.metrics) rows.push({ kind: 'metric', key: m.metric, layer: m.layer, group: m.protein, a: m.a, b: m.b, delta: m.delta })
  return toCsv(rows, ['kind', 'key', 'group', 'layer', 'time', 'a', 'b', 'delta', 'ratio', 'log2ratio'])
}

/** Static, self-contained HTML snapshot of comparison mode, for a fix PR's before/after evidence. */
export function reportHtml(c: Comparison, root: HTMLElement): string {
  const figs = [...root.querySelectorAll<HTMLElement>('[data-figure]')].map((el) => {
    const title = el.closest('section')?.querySelector('h3')?.textContent ?? ''
    let svg: string
    try {
      svg = figureToSvg(el).svg
    } catch {
      svg = '<p>(figure could not be serialised)</p>'
    }
    return `<h2>${esc(title)}</h2>${svg}`
  })
  const pa = c.provenance.a
  const pb = c.provenance.b
  const issueRow = c.issues.available
    ? `<tr><th>open known issues only in A (fixed in B?)</th><td colspan=2>${esc(c.issues.onlyA.join(', ') || 'none')}</td></tr><tr><th>open only in B (new)</th><td colspan=2>${esc(c.issues.onlyB.join(', ') || 'none')}</td></tr><tr><th>open in both</th><td colspan=2>${esc(c.issues.both.join(', ') || 'none')}</td></tr>`
    : '<tr><th>known issues</th><td colspan=2>not recorded in at least one bundle</td></tr>'
  const gofRows = ['overall', ...Object.keys(c.gof.a.layers)].map((l) => {
    const a = l === 'overall' ? c.gof.a.overall : c.gof.a.layers[l]
    const b = l === 'overall' ? c.gof.b.overall : c.gof.b.layers[l]
    const f = (x?: number) => (x === undefined || !Number.isFinite(x) ? 'n/a' : x.toPrecision(5))
    return `<tr><td>${esc(l)}</td><td>${f(a?.r2)}</td><td>${f(b?.r2)}</td><td>${f(b && a ? b.r2 - a.r2 : NaN)}</td><td>${f(a?.rmse)}</td><td>${f(b?.rmse)}</td><td>${f(b && a ? b.rmse - a.rmse : NaN)}</td></tr>`
  })
  return `<!doctype html><html><head><meta charset="utf-8"><title>PhosKinTime run comparison ${esc(pa.bundleId)} vs ${esc(pb.bundleId)}</title>
<style>body{font-family:system-ui,sans-serif;max-width:1200px;margin:20px auto;color:#1d2330}table{border-collapse:collapse;font-size:13px}td,th{border:1px solid #ddd;padding:3px 8px;text-align:left}h2{font-size:16px;margin-top:28px}svg{max-width:100%;height:auto}</style></head><body>
<h1>Run comparison: A (before) vs B (after)</h1>
<p>Generated by PhosKinTime-Vis ${esc(__APP_VERSION__)} on ${esc(new Date().toISOString())}. Static snapshot: figures are SVG; all deltas are in the accompanying CSV.</p>
<table><tr><th></th><th>A (before)</th><th>B (after)</th></tr>
<tr><th>bundle</th><td>${esc(pa.label)} <code>${esc(pa.bundleId)}</code></td><td>${esc(pb.label)} <code>${esc(pb.bundleId)}</code></td></tr>
<tr><th>sha256</th><td>${esc(pa.verify)}</td><td>${esc(pb.verify)}</td></tr>
<tr><th>PhosKinTime</th><td>${esc(pa.version)}</td><td>${esc(pb.version)}</td></tr>
<tr><th>commit</th><td><code>${esc(pa.commit)}</code></td><td><code>${esc(pb.commit)}</code></td></tr>
<tr><th>config sha256</th><td><code>${esc(pa.config)}</code></td><td><code>${esc(pb.config)}</code>${c.provenance.sameConfig ? ' (same)' : ' (differs)'}</td></tr>
${issueRow}
<tr><th>parameter alignment</th><td colspan=2>${esc(c.params.mode)}: ${esc(c.params.reason)} Only in A: ${esc(c.params.onlyA.join(', ') || 'none')}. Only in B: ${esc(c.params.onlyB.join(', ') || 'none')}.</td></tr>
<tr><th>state alignment</th><td colspan=2>${c.statesAligned ? 'same state_order_sha256' : 'state order differs: paired by state name'}. States only in A: ${esc(c.traj.onlyA.join(', ') || 'none')}; only in B: ${esc(c.traj.onlyB.join(', ') || 'none')}.</td></tr>
</table>
<h2>Goodness of fit (best fit), A vs B</h2>
<table><tr><th>subset</th><th>R² A</th><th>R² B</th><th>ΔR²</th><th>RMSE A</th><th>RMSE B</th><th>ΔRMSE</th></tr>${gofRows.join('')}</table>
${figs.join('\n')}
</body></html>`
}
